#!/usr/bin/env python3
"""Embed a .p8 text cart as C arrays: the Lua source plus the decoded
asset sections (gfx/map/gff), so the SNES ROM needs no cart parser.
Mirrors runp8.c's loader semantics (left pixel = low nibble for gfx,
byte pairs for map/gff)."""
import sys


def hexv(c):
    try:
        return int(c, 16)
    except ValueError:
        return None


def main(src, out, frames=8, inputfile=None):
    inputs = []
    if inputfile:
        for ln in open(inputfile):
            ln = ln.strip()
            if ln:
                inputs.append(int(ln, 16) & 0xFFFF)
    lua = []
    gfx, gmap, gff = [], [], []
    sec = None
    for line in open(src, encoding="utf-8"):
        t = line.rstrip("\n")
        if t.startswith("__"):
            sec = {"__lua__": "lua", "__gfx__": "gfx", "__map__": "map",
                   "__gff__": "gff"}.get(t.strip(), "skip")
            continue
        if sec == "lua":
            lua.append(t + "\n")
        elif sec == "gfx":
            digs = [hexv(c) for c in t if hexv(c) is not None]
            for i in range(0, len(digs) - 1, 2):
                gfx.append(digs[i] | (digs[i + 1] << 4))  # left px low nibble
        elif sec in ("map", "gff"):
            digs = [hexv(c) for c in t if hexv(c) is not None]
            arr = gmap if sec == "map" else gff
            for i in range(0, len(digs) - 1, 2):
                arr.append((digs[i] << 4) | digs[i + 1])  # "ab" -> 0xab

    import io
    src_bytes = "".join(lua).encode("utf-8")
    buf = io.StringIO()
    f = buf
    if True:
        f.write("/* generated by tools/cart2c.py from %s - do not edit */\n" % src)
        f.write("static const char cart_lua[%d] = {\n" % (len(src_bytes) + 1))
        for i in range(0, len(src_bytes), 16):
            f.write("  " + ",".join(str(b) for b in src_bytes[i:i + 16]) + ",\n")
        f.write("  0\n};\n")
        f.write("static const unsigned int cart_lua_len = %d;\n" % len(src_bytes))
        for name, arr, base in (("gfx", gfx, "0x0000"), ("map", gmap, "0x2000"),
                                ("gff", gff, "0x3000")):
            f.write("static const unsigned char cart_%s[%d] = {\n"
                    % (name, max(len(arr), 1)))
            if arr:
                for i in range(0, len(arr), 16):
                    f.write("  " + ",".join(str(b) for b in arr[i:i + 16]) + ",\n")
            else:
                f.write("  0\n")
            f.write("};\n")
            f.write("static const unsigned int cart_%s_len = %d; /* -> %s */\n"
                    % (name, len(arr), base))
        # frame count and per-frame player-0 button masks (M4 parity)
        f.write("static const int cart_frames = %d;\n" % frames)
        f.write("static const unsigned int cart_input[%d] = {\n  "
                % max(len(inputs), 1))
        f.write(",".join(str(m) for m in inputs) if inputs else "0")
        f.write("\n};\n")
        f.write("static const unsigned int cart_input_len = %d;\n" % len(inputs))
    # write-if-changed: only bump the file's mtime when the content
    # actually differs, so switching CART reliably rebuilds p8main.o
    # (mtime races don't matter) without needless rebuilds otherwise.
    new = buf.getvalue()
    try:
        old = open(out, encoding="utf-8").read()
    except OSError:
        old = None
    if new != old:
        open(out, "w").write(new)
        print("cart2c: %s -> %s (lua %dB, gfx %dB, map %dB, gff %dB)"
              % (src, out, len(src_bytes), len(gfx), len(gmap), len(gff)))
    else:
        print("cart2c: %s unchanged" % out)


if __name__ == "__main__":
    # cart2c.py src out [frames] [inputfile]
    fr = int(sys.argv[3]) if len(sys.argv) > 3 else 8
    inp = sys.argv[4] if len(sys.argv) > 4 else None
    main(sys.argv[1], sys.argv[2], fr, inp)

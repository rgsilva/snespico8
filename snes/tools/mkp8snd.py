#!/usr/bin/env python3
"""Generate the SPC700 driver's data tables: the 8 PICO-8 waveforms as
looped BRR samples, plus the PICO-8 pitch -> DSP-P table.

Waveforms are 32-sample single-cycle loops (two BRR blocks, filter 0), in
PICO-8 order 0..7: triangle, tilted saw, saw, square, pulse, organ, noise,
phaser. Noise (6) is a placeholder cycle -- the driver plays it through the
DSP noise generator (NON), not this sample. Phaser (7) is a static
approximation (its time-varying character comes from the effect column in
M6c); marked VERIFY, ear-tuned against real PICO-8.

Pitch: PICO-8 pitch p (0..63) is MIDI note p+36, f = 440 * 2^((p-33)/12).
A 32-sample single-cycle loop at DSP rate 32000 needs P = f * 32 / 32000 *
4096 = f * 4.096 to sound one cycle per period. Output: WLA-SPC700 source.
"""
import math
import sys


def brr_blocks(samples, shift=12):
    """samples: 4-bit signed ints (-8..7), length a multiple of 16.
    Emits BRR blocks (filter 0); the final block sets loop+end so the DSP
    loops the whole cycle forever (directory loop ptr = sample start)."""
    out = []
    nb = len(samples) // 16
    for b in range(nb):
        last = b == nb - 1
        hdr = (shift << 4) | (0b11 if last else 0)   # filter 0; loop+end last
        blk = [hdr]
        for i in range(8):
            hi = samples[b * 16 + i * 2] & 0xF
            lo = samples[b * 16 + i * 2 + 1] & 0xF
            blk.append((hi << 4) | lo)
        out.append(blk)
    return out


def q(x):
    """clamp a float in [-1,1] to a 4-bit signed BRR nibble (-7..7)."""
    return max(-7, min(7, int(round(x * 7))))


N = 32
def build():
    tri, tsaw, saw, sqr, pulse, organ, noise, phaser = ([] for _ in range(8))
    for i in range(N):
        t = i / N                                  # phase 0..1
        # 0 triangle: symmetric, +1 -> -1 -> +1
        tri.append(q(1 - 4 * abs(t - 0.5)))
        # 1 tilted saw: rises for 3/4, falls for 1/4 (asymmetric triangle)
        tsaw.append(q((t / 0.75) * 2 - 1 if t < 0.75 else (1 - t) / 0.25 * 2 - 1))
        # 2 saw: linear ramp -1 -> +1 (discontinuity at wrap)
        saw.append(q(2 * t - 1))
        # 3 square: 50% duty
        sqr.append(q(1 if t < 0.5 else -1))
        # 4 pulse: ~1/3 duty
        pulse.append(q(1 if t < 1 / 3 else -1))
        # 5 organ: fundamental + octave (additive, organ-ish)
        organ.append(q(0.7 * math.sin(2 * math.pi * t) + 0.3 * math.sin(4 * math.pi * t)))
        # 6 noise: placeholder cycle (unused; DSP NON drives the voice)
        noise.append(q(math.sin(2 * math.pi * t)))
        # 7 phaser (VERIFY): narrow-ish pulse, ear-tuned; time sweep = M6c
        phaser.append(q(1 if t < 0.4 else -1))
    return [("wav_tri", tri), ("wav_tsaw", tsaw), ("wav_saw", saw),
            ("wav_sqr", sqr), ("wav_pulse", pulse), ("wav_organ", organ),
            ("wav_noise", noise), ("wav_phaser", phaser)]


out = ["; generated by tools/mkp8snd.py -- do not edit", ""]
for name, s in build():
    out.append("%s:" % name)
    for blk in brr_blocks(s):
        out.append("    .db " + ", ".join("$%02X" % b for b in blk))
out.append("")

out.append("pitch_tab:                   ; PICO-8 pitch 0..63 -> DSP P (32-sample loop)")
row = []
for p in range(64):
    f = 440.0 * 2 ** ((p - 33) / 12.0)
    row.append(min(0x3FFF, max(1, int(round(f * 4.096)))))
for i in range(0, 64, 8):
    out.append("    .dw " + ", ".join("$%04X" % v for v in row[i:i + 8]))
out.append("")

with open(sys.argv[1], "w") as f:
    f.write("\n".join(out) + "\n")
print("%s: 8 PICO-8 waves + 64-entry pitch table" % sys.argv[1])

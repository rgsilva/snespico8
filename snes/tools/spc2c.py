#!/usr/bin/env python3
"""Convert a WLA-SPC700 64 KB RAM image into a C blob for the Calypsi ROM.

The driver is assembled with .ORG $0200; apu_upload (p8spc.c) streams LEN
bytes from that address into SPC RAM at boot and jumps to ENTRY (past the
16-byte sample directory at $0200). Emitting a C array keeps the whole SPC
driver inside the Calypsi build with no extra link step.
"""
import sys

ADDR, ENTRY, LEN = 0x0200, 0x0210, 1024

data = open(sys.argv[1], "rb").read()
blob = data[ADDR:ADDR + LEN]
with open(sys.argv[2], "w") as f:
    f.write("/* generated by tools/spc2c.py from the WLA-SPC700 image */\n")
    f.write("#ifndef P8SPC_BLOB_H\n#define P8SPC_BLOB_H\n")
    f.write("#define P8SPC_ADDR  0x%04x\n" % ADDR)
    f.write("#define P8SPC_ENTRY 0x%04x\n" % ENTRY)
    f.write("#define P8SPC_LEN   %d\n" % LEN)
    f.write("static const unsigned char p8spc_blob[P8SPC_LEN] = {\n")
    for i in range(0, LEN, 16):
        f.write("  " + ",".join(str(b) for b in blob[i:i + 16]) + ",\n")
    f.write("};\n#endif\n")
print("%s: %d bytes from 0x%04x, entry 0x%04x" % (sys.argv[2], LEN, ADDR, ENTRY))

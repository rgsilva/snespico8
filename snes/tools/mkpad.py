#!/usr/bin/env python3
"""Generate the M9 roulette pad TU (snes/Makefile PERTURB=n).

n dummy functions + an odd-sized const array shift every downstream
farcode/const address; p8_pad_probe references all of it and is itself
called once from main(), so the linker cannot strip any of it (it DOES
strip unreferenced sections -- verified: an unanchored pad left
luaV_execute at the same address). p8_pad_probe exists at n=0 too (as
identity), so p8main can call it unconditionally. Write-if-changed to
keep make deps quiet.

Usage: mkpad.py out.c n
"""
import sys


def main(out, n):
    n = int(n)
    # n is a SIZE knob: n const bytes + (n % 7) small functions. Layout
    # perturbation needs variety, not volume -- an early version emitted
    # n FUNCTIONS, and the probe summing 3571 calls in one expression
    # killed the compiler mid-roulette.
    nfn = n % 7
    lines = ["/* generated by tools/mkpad.py -- M9 roulette pad, n=%d */" % n]
    for i in range(nfn):
        lines.append("long p8_pad_fn%d(long x) { return x + %d; }" % (i, i))
    if n:
        lines.append("const char p8_pad_bytes[%d] = {7};" % n)
    terms = ["x"] + ["p8_pad_fn%d(x)" % i for i in range(nfn)]
    if n:
        terms.append("(long)p8_pad_bytes[0]")
    lines.append("long p8_pad_probe(long x) { return %s; }" % " + ".join(terms))
    body = "\n".join(lines) + "\n"
    try:
        if open(out).read() == body:
            return
    except OSError:
        pass
    open(out, "w").write(body)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])

#!/usr/bin/env python3
"""Generate m7tables.inc: PICO-8 palette in BGR555 and the 4bpp->8bpp
expansion LUT (one word per source byte: low byte = left pixel = low
nibble, high byte = right pixel = high nibble)."""
import sys

PICO8 = [
    0x000000, 0x1D2B53, 0x7E2553, 0x008751,
    0xAB5236, 0x5F574F, 0xC2C3C7, 0xFFF1E8,
    0xFF004D, 0xFFA300, 0xFFEC27, 0x00E436,
    0x29ADFF, 0x83769C, 0xFF77A8, 0xFFCCAA,
]


def bgr555(rgb):
    r, g, b = (rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF
    return ((b >> 3) << 10) | ((g >> 3) << 5) | (r >> 3)


def main(out):
    with open(out, "w") as f:
        f.write("; generated by tools/mkm7.py - do not edit\n")
        f.write("PalPico8:\n")
        for i in range(0, 16, 8):
            row = ", ".join(f"${bgr555(c):04X}" for c in PICO8[i:i + 8])
            f.write(f"  .dw {row}\n")
        f.write("LUT16:\n")
        for b in range(0, 256, 8):
            row = ", ".join(f"${((v >> 4) << 8) | (v & 0x0F):04X}"
                            for v in range(b, b + 8))
            f.write(f"  .dw {row}\n")


if __name__ == "__main__":
    main(sys.argv[1])

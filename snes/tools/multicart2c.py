#!/usr/bin/env python3
"""Bundle several .p8 text carts into one C header (cart_multi.h): each
cart's Lua source + decoded asset sections as static arrays, plus a
descriptor table (MultiCart carts[]) and cart_count. The SNES menu ROM
(p8main.c built with -DP8_MULTICART) picks one at runtime and boots it.

Reuses cart2c's section parsers verbatim so a bundled cart decodes exactly
like a stand-alone one."""
import sys
import os
import io
from cart2c import hexv, sfx_bytes, music_bytes


def parse_cart(src):
    """.p8 -> (lua_bytes, gfx, map, gff, sfx, music). Mirrors cart2c.main's
    section loop (same nibble/byte rules)."""
    lua = []
    gfx, gmap, gff, sfx, music = [], [], [], [], []
    sec = None
    for line in open(src, encoding="utf-8"):
        t = line.rstrip("\n")
        if t.startswith("__"):
            sec = {"__lua__": "lua", "__gfx__": "gfx", "__map__": "map",
                   "__gff__": "gff", "__sfx__": "sfx",
                   "__music__": "music"}.get(t.strip(), "skip")
            continue
        if sec == "lua":
            lua.append(t + "\n")
        elif sec == "gfx":
            digs = [hexv(c) for c in t if hexv(c) is not None]
            for i in range(0, len(digs) - 1, 2):
                gfx.append(digs[i] | (digs[i + 1] << 4))
        elif sec in ("map", "gff"):
            digs = [hexv(c) for c in t if hexv(c) is not None]
            arr = gmap if sec == "map" else gff
            for i in range(0, len(digs) - 1, 2):
                arr.append((digs[i] << 4) | digs[i + 1])
        elif sec == "sfx" and len(sfx) < 64 * 68:
            b = sfx_bytes(t)
            if b:
                sfx.extend(b)
        elif sec == "music" and len(music) < 64 * 4:
            b = music_bytes(t)
            if b:
                music.extend(b)
    return "".join(lua).encode("utf-8"), gfx, gmap, gff, sfx, music


def label(src):
    """Menu label = the file's base name without .p8, capped to the width
    the 128px menu can show (~28 chars at 4px/glyph, leave margin)."""
    base = os.path.basename(src)
    if base.endswith(".p8"):
        base = base[:-3]
    return base[:20]


def emit_bytes(f, name, data, as_char=False):
    """Emit a static const array; NUL-terminate char arrays (Lua source)."""
    n = len(data) + (1 if as_char else 0)
    f.write("static const %s %s[%d] = {\n"
            % ("char" if as_char else "unsigned char", name, max(n, 1)))
    if data:
        for i in range(0, len(data), 16):
            f.write("  " + ",".join(str(b) for b in data[i:i + 16]) + ",\n")
        if as_char:
            f.write("  0\n")
    else:
        f.write("  0\n")
    f.write("};\n")


def main(out, srcs, frames=1000000000):
    buf = io.StringIO()
    f = buf
    f.write("/* generated by tools/multicart2c.py - do not edit */\n")
    f.write("typedef struct {\n"
            "  const char *lua; unsigned lua_len;\n"
            "  const unsigned char *gfx; unsigned gfx_len;\n"
            "  const unsigned char *map; unsigned map_len;\n"
            "  const unsigned char *gff; unsigned gff_len;\n"
            "  const unsigned char *music; unsigned music_len;\n"
            "  const unsigned char *sfx; unsigned sfx_len;\n"
            "  const char *name; long frames;\n"
            "} MultiCart;\n")
    metas = []
    for idx, src in enumerate(srcs):
        lua_b, gfx, gmap, gff, sfx, music = parse_cart(src)
        emit_bytes(f, "c%d_lua" % idx, list(lua_b), as_char=True)
        emit_bytes(f, "c%d_gfx" % idx, gfx)
        emit_bytes(f, "c%d_map" % idx, gmap)
        emit_bytes(f, "c%d_gff" % idx, gff)
        emit_bytes(f, "c%d_music" % idx, music)
        emit_bytes(f, "c%d_sfx" % idx, sfx)
        f.write('static const char c%d_name[] = "%s";\n' % (idx, label(src)))
        metas.append((idx, len(lua_b), len(gfx), len(gmap),
                      len(gff), len(music), len(sfx)))
    f.write("static const MultiCart carts[%d] = {\n" % len(srcs))
    for (idx, ll, gl, ml, fl, mul, sl) in metas:
        f.write("  { c%d_lua, %d, c%d_gfx, %d, c%d_map, %d, c%d_gff, %d, "
                "c%d_music, %d, c%d_sfx, %d, c%d_name, %d },\n"
                % (idx, ll, idx, gl, idx, ml, idx, fl,
                   idx, mul, idx, sl, idx, frames))
    f.write("};\n")
    f.write("static const int cart_count = %d;\n" % len(srcs))

    new = buf.getvalue()
    try:
        old = open(out, encoding="utf-8").read()
    except OSError:
        old = None
    if new != old:
        open(out, "w").write(new)
        print("multicart2c: %d carts -> %s (%s)"
              % (len(srcs), out, ", ".join(label(s) for s in srcs)))
    else:
        print("multicart2c: %s unchanged" % out)


if __name__ == "__main__":
    # multicart2c.py out cart1.p8 cart2.p8 ...
    if len(sys.argv) < 3:
        sys.exit("usage: multicart2c.py out.h cart1.p8 [cart2.p8 ...]")
    main(sys.argv[1], sys.argv[2:])

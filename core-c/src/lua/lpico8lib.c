static int pico8_tostr(lua_State *l) {
    char buffer[24];
    char const *s = buffer;
    unsigned int flags = 0;
    if (lua_isboolean(l, 2)) {
        flags = lua_toboolean(l, 2) ? 1 : 0;
    }
    else if (lua_isnumber(l, 2)) {
        flags = (unsigned int)lua_tointeger(l, 2);
    }
    switch (lua_type(l, 1))
    {
        case LUA_TNONE:
            buffer[0] = '\0';
            break;
        case LUA_TNUMBER: {
            long x = tobits(l, 1);
            if (flags) {
                unsigned long b = (unsigned long)(unsigned LUA_INT32)x;
                if ((flags & 0x3u) == 0x3u) {
                    sprintf(buffer, "0x%04lx%04lx", (b >> 16) & 0xffffu, b & 0xffffu);
                }
                else if (flags & 0x2u) {
                    sprintf(buffer, "%ld", (long)(LUA_INT32)b);
                }
                else {
                    sprintf(buffer, "0x%04lx.%04lx", (b >> 16) & 0xffffu, b & 0xffffu);
                }
            } else {
                p8_fix2str(buffer, x);
            }
            break;
        }
        case LUA_TSTRING:
            lua_pushvalue(l, 1);
            return 1;
        case LUA_TBOOLEAN: s = lua_toboolean(l, 1) ? "true" : "false"; break;
        case LUA_TTABLE:
            if (luaL_callmeta(l, 1, "__tostring")) {
                luaL_tolstring(l, 1, NULL);
                return 1;
            }
            /* fall through */
        case LUA_TFUNCTION:
            if (flags) {
                luaL_tolstring(l, 1, NULL);
                return 1;
            }
            /* fall through */
        default: sprintf(buffer, "[%s]", luaL_typename(l, 1)); break;
    }
    lua_pushstring(l, s);
    return 1;
}

static int pico8_tonum(lua_State *l) {
    lua_Number ret;
    switch (lua_type(l, 1))
    {
        case LUA_TSTRING: {
            char const *s = lua_tostring(l, 1);
            unsigned int flags = lua_gettop(l) >= 2 ? (unsigned int)lua_tointeger(l, 2) : 0;
            if (flags & 0x1u) {
                /* raw hex digits -> raw bits (z8lua had an unbounded
                   write here; cap at 8 digits and terminate) */
                char buffer[9];
                size_t i;
                unsigned long bits;
                for (i = 0; i < 8 && s[i] != '\0'; ++i) {
                    buffer[i] = isxdigit((unsigned char)s[i]) ? s[i] : '0';
                }
                buffer[i] = '\0';
                bits = strtoul(buffer, NULL, 16);
                if (flags & 0x2u) bits >>= 16;
                /* z8lua's (lua_Number)bits invokes the scaling ctor */
                lua_pushnumber(l, (lua_Number)p8fix_fromint((long)bits));
                return 1;
            }
            else if (flags & 0x2u) {
                unsigned long bits = strtoul(s, NULL, 10);
                bits >>= 16;
                lua_pushnumber(l, (lua_Number)p8fix_fromint((long)bits));
                return 1;
            }
            if (!luaO_str2d(s, strlen(s), &ret)) return 0;
            break;
        }
        case LUA_TNUMBER: ret = lua_tonumber(l, 1); break;
        case LUA_TBOOLEAN: {
            /* Calypsi -O0 clobbers a ?: ternary passed directly as a call
               argument (bugs/calypsi-ternary-arg-clobber.c) — the result
               in A is overwritten before use. Force it into a named local. */
            long bv = lua_toboolean(l, 1) ? 1 : 0;
            ret = (lua_Number)p8fix_fromint(bv);
            break;
        }
        default: return 0;
    }
    lua_pushnumber(l, ret);
    return 1;
}

/* sub(s, i, [j]): PICO-8 global, string.sub semantics (1-based,
   negative indices from the end, j defaults to -1) */
static int pico8_sub(lua_State *l) {
    size_t len;
    char const *s = luaL_checklstring(l, 1, &len);
    long i = p8fix_toint(tobits(l, 2));
    long j = lua_isnoneornil(l, 3) ? -1 : p8fix_toint(tobits(l, 3));
    if (i < 0) { i = (long)len + i + 1; if (i < 1) i = 1; }
    else if (i == 0) i = 1;
    if (j < 0) j = (long)len + j + 1;
    else if (j > (long)len) j = (long)len;
    if (i > j) {
        lua_pushlstring(l, "", 0);
        return 1;
    }
    lua_pushlstring(l, s + (i - 1), (size_t)(j - i + 1));
    return 1;
}

static int pico8_chr(lua_State *l) {
    char s[248];
    size_t numargs = (size_t)lua_gettop(l);
    size_t i;
    if (numargs > sizeof(s)) numargs = sizeof(s);
    for (i = 0; i < numargs; i++) {
        s[i] = (char)(unsigned char)p8fix_toint(tobits(l, (int)i + 1));
    }
    lua_pushlstring(l, s, numargs);
    return 1;
}

static int pico8_ord(lua_State *l) {
    size_t len;
    long n = 0;
    long count = 1;
    long i;
    char const *s = luaL_checklstring(l, 1, &len);
    if (!lua_isnone(l, 3)) {
        if (!lua_isnumber(l, 3)) return 0;
        count = p8fix_toint(tobits(l, 3));
    }
    if (!lua_isnone(l, 2)) {
        if (!lua_isnumber(l, 2)) return 0;
        n = p8fix_toint(tobits(l, 2)) - 1;
    }
    if (n < 0 || (size_t)n >= len || count < 1)
        return 0;
    if ((size_t)(n + count) > len)
        count = (long)(len - (size_t)n);
    lua_checkstack(l, (int)count);
    for (i = 0; i < count; ++i)
        lua_pushnumber(l, (lua_Number)p8fix_fromint((unsigned char)s[n + i]));
    return (int)count;
}

static int pico8_split(lua_State *l) {
    size_t count = 0, hlen;
    char const *haystack;
    char const *end;
    char const *parser;
    long size = 0;
    char needle = ',';
    int convert;
    if (lua_isnil(l, 1) || lua_isnone(l, 1))
        return 0;
    haystack = luaL_checklstring(l, 1, &hlen);
    if (!haystack)
        return 0;
    lua_newtable(l);
    if (lua_isnumber(l, 2)) {
        size = p8fix_toint(tobits(l, 2));
        if (size <= 0)
            size = 1;
    } else if (lua_isstring(l, 2)) {
        needle = *lua_tostring(l, 2);
    }
    convert = lua_isnone(l, 3) || lua_toboolean(l, 3);
    end = haystack + hlen + (!size && needle);
    for (parser = haystack; parser < end; ) {
        lua_Number num;
        char const *next = size ? parser + size
                         : needle ? (char const*)memchr(parser, needle, (size_t)(end - parser)) : parser + 1;
        char saved;
        if (!next || next > end)
            next = haystack + hlen;
        saved = *next; /* temporarily null-terminate inside the string */
        *(char *)next = '\0';
        if (convert && luaO_str2d(parser, (size_t)(next - parser), &num))
            lua_pushnumber(l, num);
        else
            lua_pushlstring(l, parser, (size_t)(next - parser));
        *(char *)next = saved;
        lua_rawseti(l, -2, (int)++count);
        parser = next + (!size && needle);
    }
    return 1;
}

/* unpack(t, [i], [j]): PICO-8 global (Lua's table.unpack; ltablib is
   not linked) */
static int pico8_unpack(lua_State *l) {
    long i = lua_isnoneornil(l, 2) ? 1 : p8fix_toint(tobits(l, 2));
    long j = lua_isnoneornil(l, 3) ? (long)lua_rawlen(l, 1) : p8fix_toint(tobits(l, 3));
    long n = j - i + 1, k;
    if (n <= 0) return 0;
    if (n > 2000 || !lua_checkstack(l, (int)n))
        return luaL_error(l, "too many results to unpack");
    for (k = i; k <= j; k++)
        lua_rawgeti(l, 1, (int)k);
    return (int)n;
}


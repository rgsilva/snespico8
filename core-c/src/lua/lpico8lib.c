/* PICO-8 language library — C port of z8lua's lpico8lib.c (WTFPL,
** Copyright (c) 2016-2024 Sam Hocevar), adapted for the snespico8 C
** fix32 engine (p8num.c): no int64, no C++ operators. The sin/atan
** lookup tables (trigtables.h) are z8lua's, generated from PICO-8 to
** guarantee bit-exact trigonometry.
**
** Table helpers (add/del/...) and rnd/srand are NOT here: they live in
** p8.c because rnd's state is machine RAM (0x5f44). */

static int pico8_abs(lua_State *l) {
    long a = tobits(l, 1);
    pushbits(l, a < 0 ? p8fix_unm(a) : a);
    return 1;
}

static int pico8_sgn(lua_State *l) {
    pushbits(l, p8fix_fromint(tobits(l, 1) >= 0 ? 1 : -1));
    return 1;
}


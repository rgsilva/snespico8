#!/usr/bin/env python3
"""Generate src/p8font.h from fake-08's fontdata.cpp (MIT, itself taken
from tac08). The source is a 128x128 '0'/'7' pixel grid: 16x16 glyphs of
8x8, PICO-8 character order (0-255). Output: 8 row-bytes per glyph, bit x
(LSB = leftmost pixel) set = pixel on."""
import re
import sys


# Corrections vs current real PICO-8 (v0.2.6b), pinned by rendering each
# glyph on the real console and diffing pixels (fake-08's grid predates
# these tweaks): puny-e (69) and puny-l (76) bottom row, ampersand row 2.
OVERRIDES = {69: {4: 0x06}, 76: {4: 0x06}, 38: {2: 0x06}}

def main(src, out):
    text = open(src, encoding="utf-8").read()
    m = re.search(r'font_ss_str\s*=\s*R"\((.*?)\)"', text, re.S)
    if not m:
        sys.exit("mkfont: font_ss_str not found")
    rows = [ln.strip() for ln in m.group(1).splitlines() if ln.strip()]
    rows = [r for r in rows if len(r) == 128 and set(r) <= {"0", "7"}]
    if len(rows) > 128 or len(rows) < 120:
        sys.exit(f"mkfont: expected ~128 pixel rows, got {len(rows)}")
    while len(rows) < 128:  # source trims trailing empty rows
        rows.append("0" * 128)
    with open(out, "w") as f:
        f.write("/* generated by tools/mkfont.py from fake-08 fontdata.cpp\n"
                "   (MIT, https://github.com/jtothebell/fake-08, font grid\n"
                "   originally from tac08) - do not edit */\n")
        f.write("static const unsigned char p8_font[256][8] = {\n")
        for c in range(256):
            # the sheet starts at char 16 (0-15 are control chars, blank)
            if c < 16:
                f.write("  {0,0,0,0,0,0,0,0}, /* %d */\n" % c)
                continue
            block, col = (c - 16) >> 4, (c - 16) & 15
            bs = []
            for y in range(8):
                row = rows[block * 8 + y]
                b = 0
                for x in range(8):
                    if row[col * 8 + x] == "7":
                        b |= 1 << x
                bs.append(b)
            for row_i, val in OVERRIDES.get(c, {}).items():
                bs[row_i] = val
            f.write("  {" + ",".join(f"0x{b:02x}" for b in bs) + "},"
                    + (f" /* {chr(c)!r} */\n" if 32 <= c < 127 else f" /* {c} */\n"))
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
